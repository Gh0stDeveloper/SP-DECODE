#!/usr/bin/env python3
"""Generate fixed-origin HTTPS reverse proxy; deny admin by default."""
from __future__ import annotations
import ipaddress, re, sys
if len(sys.argv) not in (2,3):
    raise SystemExit("Usage: nginx-config.py DNS_HOST [ADMIN_CIDR]")
domain=sys.argv[1]
if (not re.fullmatch(r"[A-Za-z0-9](?:[A-Za-z0-9.-]{1,248})[A-Za-z0-9]",domain)
        or "." not in domain or ".." in domain or domain.endswith(".local")):
    raise SystemExit("Invalid DNS hostname")
if len(sys.argv)==3:
    network=ipaddress.ip_network(sys.argv[2],strict=False)
    if network.prefixlen != network.max_prefixlen:
        raise SystemExit("Admin CIDR must be one exact operator IP (/32 IPv4 or /128 IPv6)")
    cidr=str(network)
else:
    cidr="127.0.0.1/32"
print(f"""# Generated by SP-DECODE C8; edit via controlled deployment only.
server {{
    listen 80;
    server_name {domain};
    root /var/www/spdecode-acme;
    location ^~ /.well-known/acme-challenge/ {{ try_files $uri =404; }}
    location / {{ return 308 https://{domain}$request_uri; }}
}}
server {{
    listen 443 ssl;
    server_name {domain};
    ssl_certificate /etc/letsencrypt/live/{domain}/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/{domain}/privkey.pem;
    ssl_protocols TLSv1.2 TLSv1.3;
    client_max_body_size 12m;
    client_body_timeout 25s;
    client_header_timeout 10s;
    keepalive_timeout 10s;
    server_tokens off;
    add_header Strict-Transport-Security "max-age=31536000" always;
    add_header X-Content-Type-Options "nosniff" always;
    add_header Referrer-Policy "no-referrer" always;
    # Sensitive admin endpoints are unreachable except from explicit operator IP.
    location ^~ /api/admin/ {{
        allow {cidr};
        deny all;
        access_log off;
        proxy_pass http://127.0.0.1:3000;
        proxy_http_version 1.1;
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $remote_addr;
        proxy_set_header X-Forwarded-Proto https;
        proxy_set_header Connection "";
        proxy_connect_timeout 5s;
        proxy_read_timeout 30s;
        proxy_redirect off;
    }}
    location ^~ /admin {{
        allow {cidr};
        deny all;
        proxy_pass http://127.0.0.1:3000;
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $remote_addr;
        proxy_set_header X-Forwarded-Proto https;
        proxy_redirect off;
    }}
    location / {{
        access_log off;
        proxy_pass http://127.0.0.1:3000;
        proxy_http_version 1.1;
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $remote_addr;
        proxy_set_header X-Forwarded-Proto https;
        proxy_set_header Connection "";
        proxy_connect_timeout 5s;
        proxy_send_timeout 25s;
        proxy_read_timeout 35s;
        proxy_redirect off;
    }}
}}""")
